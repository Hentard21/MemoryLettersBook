# --- патч visual_classification (старое сохраняем в notes) ---
patched = 0
for page_num, (new_type, new_conf, reason) in RECLASSIFY.items():
    page = pages_by_num[page_num]
    vc = page.get("visual_classification")
    if not vc:
        continue
    prev = f"previous: page_type={vc['page_type']}, confidence={vc['confidence']}"
    vc["notes"] = (vc.get("notes") or []) + [prev, reason]
    vc["page_type"] = new_type
    vc["confidence"] = new_conf
    vc["review_required"] = False if new_conf >= 0.85 else vc.get("review_required", True)
    patched += 1

