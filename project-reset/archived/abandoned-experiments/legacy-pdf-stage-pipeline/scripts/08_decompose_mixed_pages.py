entities = []
for page_num in sorted(D):
    page = pages_by_num[page_num]
    hero_id = page.get("hero_id")
    for i, (etype, region_label, bbox, conf, extra) in enumerate(D[page_num], start=1):
        ent = {
            "entity_id": f"p{page_num:03d}-{etype.lower()}-{i:02d}",
            "entity_type": etype,
            "source_page": page_num,
            "region_label": region_label,
            "bbox_pct_approx": bbox,
            "bbox_note": "Приблизительно, по визуальному осмотру; точные границы — из координат фигур PPTX",
            "hero_id": hero_id,
            "hero_link_status": "probable_by_sequence" if hero_id else "unassigned",
            "confidence": conf,
            "source_quality": "pdf_reference",
            "needs_pptx_original": True,
            "needs_ocr": etype == "Letter",
            "ocr_note": "Только ручная диплом. расшифровка, массовый OCR запрещён" if etype == "Letter" else None,
            "needs_manual_review": bool(extra.get("needs_manual_review", False)),
        }
        for k in ("text_observation", "review_reason", "note", "caption_source"):
            if k in extra:
                ent[k] = extra[k]
        entities.append(ent)

